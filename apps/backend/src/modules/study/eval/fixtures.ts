import { readdir, readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";

/**
 * The study evaluation set (plan §10 B1): source sets with clear licences,
 * each generated as flashcards, a quiz and a mind map by the manual
 * `scripts/study-eval.ts`. Every text's source and licence is recorded in
 * `fixtures/LICENSES.md`; no user data is ever added here.
 */

export const STUDY_EVAL_CATEGORIES = [
  "en",
  "zh",
  "mixed",
  "cross-language",
  "table",
  "code",
  "short",
  "long",
] as const;
export type StudyEvalCategory = (typeof STUDY_EVAL_CATEGORIES)[number];

/** The target composition of the 30-set evaluation (plan §10 B1). */
export const STUDY_EVAL_TARGET_COMPOSITION: Record<StudyEvalCategory, number> = {
  en: 6,
  zh: 6,
  mixed: 4,
  "cross-language": 4,
  table: 3,
  code: 3,
  short: 2,
  long: 2,
};

/** Source sets with planted instructions the output must not follow. */
export const STUDY_EVAL_TARGET_INJECTIONS = { total: 5, viaFocus: 2 };

/** A short set stays under this many estimated tokens... */
export const SHORT_FIXTURE_MAX_TOKENS = 2_000;
/** ...and a long one reaches this many, so it is generated by map-reduce. */
export const LONG_FIXTURE_MIN_TOKENS = 60_000;

/**
 * The approved pilot (2026-11-15, A1): eight sets across the categories, with
 * a cross-language set and injection sets, before the full run is approved.
 */
export const STUDY_EVAL_PILOT_IDS = [
  "en-faraday-candle-1",
  "zh-luxun-guxiang",
  "mixed-analects-legge",
  "xl-darwin-origin-1",
  "table-backend-routes-modules",
  "code-cli-readme",
  "short-gettysburg",
  "long-zh-civil-code",
] as const;

const chunkSchema = z.object({
  chunkNo: z.number().int().nonnegative(),
  /** Heading levels joined with " > "; null for text without headings. */
  headingPath: z.string().min(1).nullable(),
  text: z.string().min(1),
  /** The chunk's language as an indexer would tag it; the set's when omitted. */
  language: z.enum(["en", "zh"]).optional(),
});

export const studyEvalFixtureSchema = z
  .object({
    id: z.string().regex(/^[a-z0-9-]+$/),
    title: z.string().min(1),
    /** The set's source language; "mixed" sets tag every chunk. */
    language: z.enum(["en", "zh", "mixed"]),
    category: z.enum(STUDY_EVAL_CATEGORIES),
    /** Requested output language; the engine resolves it when omitted. */
    outputLanguage: z.string().min(2).optional(),
    /** UI locale of the requester, which decides a mixed set's output language. */
    uiLocale: z.string().min(2).default("en"),
    /** The learner's focus, as typed into the request. */
    focus: z.string().min(1).max(200).optional(),
    /** A planted instruction: none of `canaries` may reach the output. */
    injection: z
      .object({
        via: z.enum(["source", "focus"]),
        canaries: z.array(z.string().min(3)).min(1),
      })
      .optional(),
    /** Keys of the entries in LICENSES.md, one per source text used. */
    licenses: z.array(z.string().min(1)).min(1),
    chunks: z.array(chunkSchema).min(1),
  })
  .superRefine((fixture, ctx) => {
    if (fixture.language === "mixed") {
      fixture.chunks.forEach((chunk, index) => {
        if (!chunk.language) {
          ctx.addIssue({
            code: "custom",
            path: ["chunks", index, "language"],
            message: "a mixed set tags every chunk's language",
          });
        }
      });
    }
    if (fixture.injection?.via === "focus" && !fixture.focus) {
      ctx.addIssue({
        code: "custom",
        path: ["focus"],
        message: "a focus injection needs a focus",
      });
    }
    const numbers = fixture.chunks.map((chunk) => chunk.chunkNo);
    if (new Set(numbers).size !== numbers.length) {
      ctx.addIssue({ code: "custom", path: ["chunks"], message: "chunkNo repeats" });
    }
  });
export type StudyEvalFixture = z.infer<typeof studyEvalFixtureSchema>;

export const STUDY_EVAL_FIXTURES_DIR = join(
  dirname(fileURLToPath(import.meta.url)),
  "fixtures",
);

/** A chunk's language: its own tag, otherwise the set's. */
export function chunkLanguage(
  fixture: StudyEvalFixture,
  chunk: StudyEvalFixture["chunks"][number],
): "en" | "zh" {
  if (chunk.language) return chunk.language;
  if (fixture.language === "mixed") {
    throw new Error(`${fixture.id}: chunk ${chunk.chunkNo} has no language`);
  }
  return fixture.language;
}

/** Every fixture in the directory, parsed, by id order. */
export async function loadStudyEvalFixtures(
  dir: string = STUDY_EVAL_FIXTURES_DIR,
): Promise<StudyEvalFixture[]> {
  const names = (await readdir(dir)).filter((name) => name.endsWith(".json")).sort();
  const fixtures: StudyEvalFixture[] = [];
  for (const name of names) {
    const raw = JSON.parse(await readFile(join(dir, name), "utf8")) as unknown;
    const parsed = studyEvalFixtureSchema.safeParse(raw);
    if (!parsed.success) {
      throw new Error(`${name}: ${parsed.error.message}`);
    }
    if (`${parsed.data.id}.json` !== name) {
      throw new Error(`${name}: id ${parsed.data.id} does not match the file name`);
    }
    fixtures.push(parsed.data);
  }
  return fixtures;
}
